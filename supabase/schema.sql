CREATE TABLE public.movimiento_inventario (
    id_movimiento      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_producto        BIGINT NOT NULL,
    id_sucursal        BIGINT NOT NULL,
    id_usuario         BIGINT NOT NULL,
    tipo               VARCHAR(10) NOT NULL,
    cantidad           BIGINT NOT NULL,
    stock_anterior     BIGINT NOT NULL DEFAULT 0,
    stock_resultante   BIGINT NOT NULL,
    motivo             VARCHAR(255),
    fecha_movimiento   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_movimiento_inventario PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_movimiento_producto
        FOREIGN KEY (id_producto) REFERENCES public.producto(id_producto)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_sucursal
        FOREIGN KEY (id_sucursal) REFERENCES public.sucursal(id_sucursal)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_movimiento_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_movimiento_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    CONSTRAINT chk_movimiento_cantidad CHECK (
        (tipo = 'ENTRADA' AND cantidad >= 0)
        OR (tipo = 'SALIDA' AND cantidad < 0)
        OR (tipo = 'AJUSTE')
    ),
    CONSTRAINT chk_movimiento_stock_resultante CHECK (stock_resultante >= 0)
);

CREATE INDEX idx_movimiento_producto ON public.movimiento_inventario(id_producto);
