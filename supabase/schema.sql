-- ============================================================
-- JUAMPYZEL - SCHEMA SUPABASE (PostgreSQL)
-- ============================================================
-- Este script reemplaza el esquema anterior de MySQL/Workbench.
-- Ejecutar una sola vez en el SQL Editor de Supabase
-- (o mediante: supabase db push / psql).
--
-- Incluye:
--   * Tablas (con sus constraints e indices)
--   * Datos semilla (usuarios y categorias iniciales)
--   * Vistas para consultas con agregaciones
--   * Funciones (RPC) para operaciones atomicas y reportes
--   * Row Level Security (RLS)
--
-- NOTA: El backend accede con la clave SERVICE ROLE (que ignora
-- RLS por diseno). Las politicas RLS protegen el acceso directo
-- con la publishable/anon key. No se crean politicas publicas
-- de escritura (USING true) porque romperian la seguridad.
-- ============================================================


-- ============================================================
-- 1. USUARIO
-- ============================================================

CREATE TABLE public.usuario (
    id_usuario        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR(100) NOT NULL,
    apellido          VARCHAR(100) NOT NULL,
    correo            VARCHAR(150) NOT NULL,
    password          VARCHAR(255) NOT NULL,
    rol               VARCHAR(20)  NOT NULL DEFAULT 'VENDEDOR',
    estado            BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT chk_usuario_nombre CHECK (CHAR_LENGTH(BTRIM(nombre)) >= 2),
    CONSTRAINT chk_usuario_apellido CHECK (CHAR_LENGTH(BTRIM(apellido)) >= 2),
    CONSTRAINT chk_usuario_rol CHECK (rol IN (
        'ADMINISTRADOR', 'ENCARGADO_SUCURSAL', 'VENDEDOR', 'INVENTARIO', 'TIENDA'
    ))
);

-- ============================================================
-- 2. CATEGORIA
-- ============================================================

CREATE TABLE public.categoria (
    id_categoria   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(100) NOT NULL,
    descripcion    VARCHAR(200),
    estado         BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre),
    CONSTRAINT chk_categoria_nombre CHECK (CHAR_LENGTH(BTRIM(nombre)) >= 2)
);

-- ============================================================
-- 3. PRODUCTO
-- ============================================================

CREATE TABLE public.producto (
    id_producto    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_categoria   BIGINT NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    descripcion    TEXT,
    precio         NUMERIC(10,2) NOT NULL,
    stock_minimo   BIGINT NOT NULL DEFAULT 5,
    imagen         VARCHAR(255),
    estado         BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_producto PRIMARY KEY (id_producto),
    CONSTRAINT fk_producto_categoria
        FOREIGN KEY (id_categoria) REFERENCES public.categoria(id_categoria)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_producto_precio CHECK (precio > 0),
    CONSTRAINT chk_producto_stock_minimo CHECK (stock_minimo >= 0)
);

CREATE INDEX idx_producto_categoria ON public.producto(id_categoria);
CREATE INDEX idx_producto_nombre ON public.producto(nombre);
CREATE INDEX idx_producto_estado ON public.producto(estado);

-- ============================================================
-- 4. SUCURSAL
-- ============================================================

CREATE TABLE public.sucursal (
    id_sucursal      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(100) NOT NULL,
    direccion        VARCHAR(200) NOT NULL,
    telefono         VARCHAR(20),
    id_responsable   BIGINT,
    estado           BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_sucursal PRIMARY KEY (id_sucursal),
    CONSTRAINT fk_sucursal_responsable
        FOREIGN KEY (id_responsable) REFERENCES public.usuario(id_usuario)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT uq_sucursal_nombre UNIQUE (nombre),
    -- Un encargado de sucursal solo puede estar a cargo de una sucursal.
    CONSTRAINT uq_sucursal_responsable UNIQUE (id_responsable),
    CONSTRAINT chk_sucursal_nombre CHECK (CHAR_LENGTH(BTRIM(nombre)) >= 2),
    CONSTRAINT chk_sucursal_direccion CHECK (CHAR_LENGTH(BTRIM(direccion)) >= 5)
);

-- ============================================================
-- 5. CLIENTE
-- ============================================================

CREATE TABLE public.cliente (
    id_cliente       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       BIGINT,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    telefono         VARCHAR(20),
    correo           VARCHAR(150),
    direccion        VARCHAR(200),
    fecha_registro   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT fk_cliente_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT uq_cliente_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_cliente_correo UNIQUE (correo),
    CONSTRAINT chk_cliente_nombres CHECK (CHAR_LENGTH(BTRIM(nombres)) >= 2),
    CONSTRAINT chk_cliente_apellidos CHECK (CHAR_LENGTH(BTRIM(apellidos)) >= 2)
);

CREATE INDEX idx_cliente_nombres ON public.cliente(nombres);
CREATE INDEX idx_cliente_apellidos ON public.cliente(apellidos);

-- ============================================================
-- 6. TIENDA
-- ============================================================

CREATE TABLE public.tienda (
    id_tienda        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_usuario       BIGINT,
    nombre           VARCHAR(150) NOT NULL,
    responsable      VARCHAR(100) NOT NULL,
    telefono         VARCHAR(20),
    correo           VARCHAR(150),
    direccion        VARCHAR(200) NOT NULL,
    estado           BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_tienda PRIMARY KEY (id_tienda),
    CONSTRAINT fk_tienda_usuario
        FOREIGN KEY (id_usuario) REFERENCES public.usuario(id_usuario)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT uq_tienda_usuario UNIQUE (id_usuario),
    CONSTRAINT uq_tienda_nombre UNIQUE (nombre),
    CONSTRAINT chk_tienda_nombre CHECK (CHAR_LENGTH(BTRIM(nombre)) >= 2),
    CONSTRAINT chk_tienda_responsable CHECK (CHAR_LENGTH(BTRIM(responsable)) >= 2),
    CONSTRAINT chk_tienda_direccion CHECK (CHAR_LENGTH(BTRIM(direccion)) >= 5)
);

CREATE INDEX idx_tienda_estado ON public.tienda(estado);

-- ============================================================
-- 7. INVENTARIO
-- ============================================================

CREATE TABLE public.inventario (
    id_inventario        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_producto          BIGINT NOT NULL,
    id_sucursal          BIGINT NOT NULL,
    stock_actual         BIGINT NOT NULL DEFAULT 0,
    fecha_actualizacion  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_inventario PRIMARY KEY (id_inventario),
    CONSTRAINT fk_inventario_producto
        FOREIGN KEY (id_producto) REFERENCES public.producto(id_producto)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventario_sucursal
        FOREIGN KEY (id_sucursal) REFERENCES public.sucursal(id_sucursal)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    -- Un producto solo puede tener un registro por sucursal.
    CONSTRAINT uq_inventario_producto_sucursal UNIQUE (id_producto, id_sucursal),
    CONSTRAINT chk_inventario_stock CHECK (stock_actual >= 0)
);

CREATE INDEX idx_inventario_sucursal ON public.inventario(id_sucursal);

-- Emula el comportamiento de MySQL (ON UPDATE CURRENT_TIMESTAMP):
CREATE OR REPLACE FUNCTION public.set_fecha_actualizacion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.fecha_actualizacion := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_inventario_fecha_actualizacion
    BEFORE UPDATE ON public.inventario
    FOR EACH ROW
    EXECUTE FUNCTION public.set_fecha_actualizacion();

