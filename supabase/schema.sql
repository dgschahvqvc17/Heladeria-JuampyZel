      FROM (
          SELECT estado AS name, COUNT(*) AS value
          FROM public.pedido
          GROUP BY estado
      ) t;

    SELECT COALESCE(json_agg(json_build_object('name', t.name, 'value', t.value) ORDER BY t.value DESC), '[]'::json)
      INTO v_productos_por_categoria
      FROM (
          SELECT c.nombre AS name, COUNT(p.id_producto) AS value
          FROM public.categoria c
          LEFT JOIN public.producto p ON p.id_categoria = c.id_categoria AND p.estado = TRUE
