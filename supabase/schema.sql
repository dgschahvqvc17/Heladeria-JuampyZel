CREATE OR REPLACE VIEW public.vista_productos AS
SELECT p.id_producto, p.id_categoria, p.nombre, p.descripcion, p.precio,
       p.stock_minimo, p.imagen, p.estado, p.estado AS producto_estado,
       c.nombre AS categoria_nombre,
       c.estado AS categoria_estado
FROM public.producto p
INNER JOIN public.categoria c ON c.id_categoria = p.id_categoria;

CREATE OR REPLACE VIEW public.vista_productos_activos AS
SELECT p.id_producto, p.id_categoria, p.nombre, p.descripcion, p.precio,
       p.stock_minimo, p.imagen,
       c.nombre AS categoria_nombre
FROM public.producto p
INNER JOIN public.categoria c ON c.id_categoria = p.id_categoria
WHERE p.estado = TRUE AND c.estado = TRUE;

CREATE OR REPLACE VIEW public.vista_stock_producto AS
SELECT p.id_producto, p.id_categoria, p.nombre, p.descripcion, p.precio,
       p.stock_minimo, p.imagen, p.estado,
       c.nombre AS categoria_nombre,
       COALESCE(SUM(i.stock_actual), 0) AS stock_actual,
       (COALESCE(SUM(i.stock_actual), 0) < p.stock_minimo) AS bajo_stock
FROM public.producto p
INNER JOIN public.categoria c ON c.id_categoria = p.id_categoria
LEFT JOIN public.inventario i ON i.id_producto = p.id_producto
GROUP BY p.id_producto, p.id_categoria, p.nombre, p.descripcion, p.precio,
         p.stock_minimo, p.imagen, p.estado, c.nombre;

CREATE OR REPLACE VIEW public.vista_catalogo_productos AS
SELECT p.id_producto, p.id_categoria, p.nombre, p.descripcion, p.precio,
       p.stock_minimo, p.imagen,
       c.nombre AS categoria_nombre,
       COALESCE(SUM(i.stock_actual), 0) AS stock_disponible
FROM public.producto p
INNER JOIN public.categoria c ON c.id_categoria = p.id_categoria
LEFT JOIN public.inventario i ON i.id_producto = p.id_producto
WHERE p.estado = TRUE AND c.estado = TRUE
GROUP BY p.id_producto, p.id_categoria, p.nombre, p.descripcion, p.precio,
         p.stock_minimo, p.imagen, c.nombre;

CREATE OR REPLACE VIEW public.vista_ventas AS
SELECT v.id_venta, v.id_cliente, v.id_usuario, v.id_sucursal, v.fecha_venta, v.total,
       CONCAT_WS(' ', u.nombre, u.apellido) AS usuario,
       s.nombre AS sucursal,
       CONCAT_WS(' ', c.nombres, c.apellidos) AS cliente
FROM public.venta v
INNER JOIN public.usuario u ON u.id_usuario = v.id_usuario
INNER JOIN public.sucursal s ON s.id_sucursal = v.id_sucursal
LEFT JOIN public.cliente c ON c.id_cliente = v.id_cliente;

CREATE OR REPLACE VIEW public.vista_pedidos AS
SELECT o.id_pedido, o.id_tienda, o.id_usuario, o.fecha_pedido, o.estado, o.total,
       t.nombre AS tienda
FROM public.pedido o
INNER JOIN public.tienda t ON t.id_tienda = o.id_tienda;

CREATE OR REPLACE VIEW public.vista_historial_pedido AS
SELECT h.id_historial, h.id_pedido, h.id_usuario, h.estado_anterior,
       h.estado_nuevo, h.fecha_cambio,
       CONCAT_WS(' ', u.nombre, u.apellido) AS usuario
FROM public.historial_pedido h
INNER JOIN public.usuario u ON u.id_usuario = h.id_usuario;

CREATE OR REPLACE VIEW public.vista_movimientos AS
SELECT m.id_movimiento, m.id_producto, m.id_sucursal, m.id_usuario, m.tipo,
       m.cantidad, m.stock_anterior, m.stock_resultante, m.motivo,
       m.fecha_movimiento,
       p.nombre AS producto,
       s.nombre AS sucursal,
       CONCAT_WS(' ', u.nombre, u.apellido) AS usuario
FROM public.movimiento_inventario m
INNER JOIN public.producto p ON p.id_producto = m.id_producto
INNER JOIN public.sucursal s ON s.id_sucursal = m.id_sucursal
INNER JOIN public.usuario u ON u.id_usuario = m.id_usuario;

CREATE OR REPLACE VIEW public.vista_alertas AS
SELECT a.id_alerta, a.id_inventario, a.fecha_generacion, a.estado,
       p.nombre AS producto, p.stock_minimo, i.stock_actual,
       s.nombre AS sucursal,
       CASE a.estado WHEN 'PENDIENTE' THEN 1 WHEN 'ATENDIDA' THEN 2 END AS estado_orden
FROM public.alerta_stock a
INNER JOIN public.inventario i ON i.id_inventario = a.id_inventario
INNER JOIN public.producto p ON p.id_producto = i.id_producto
INNER JOIN public.sucursal s ON s.id_sucursal = i.id_sucursal;


