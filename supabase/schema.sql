-- Registra un movimiento de inventario y actualiza stock (transaccion)
CREATE OR REPLACE FUNCTION public.registrar_movimiento_inventario(
    p_id_producto BIGINT,
    p_id_sucursal BIGINT,
    p_id_usuario BIGINT,
    p_tipo VARCHAR,
    p_cantidad BIGINT,
    p_motivo VARCHAR DEFAULT NULL
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_inventario      RECORD;
    v_stock_anterior  BIGINT;
    v_stock_resultante BIGINT;
    v_movimiento_id   BIGINT;
BEGIN
    SELECT * INTO v_inventario
    FROM public.inventario
    WHERE id_producto = p_id_producto AND id_sucursal = p_id_sucursal
    FOR UPDATE;

    v_stock_anterior := COALESCE(v_inventario.stock_actual, 0);

    IF p_tipo = 'ENTRADA' THEN
        v_stock_resultante := v_stock_anterior + p_cantidad;
    ELSIF p_tipo = 'SALIDA' THEN
        IF p_cantidad > v_stock_anterior THEN
            RAISE EXCEPTION 'Stock insuficiente. Disponible: %', v_stock_anterior;
        END IF;
        v_stock_resultante := v_stock_anterior - p_cantidad;
    ELSE
        IF p_motivo IS NULL OR CHAR_LENGTH(BTRIM(p_motivo)) < 2 THEN
            RAISE EXCEPTION 'Debe indicar el motivo del ajuste.';
        END IF;
        v_stock_resultante := p_cantidad;
    END IF;

    IF FOUND THEN
        UPDATE public.inventario
           SET stock_actual = v_stock_resultante
         WHERE id_inventario = v_inventario.id_inventario;
    ELSE
        INSERT INTO public.inventario (id_producto, id_sucursal, stock_actual)
        VALUES (p_id_producto, p_id_sucursal, v_stock_resultante);
    END IF;

    INSERT INTO public.movimiento_inventario
        (id_producto, id_sucursal, id_usuario, tipo, cantidad,
         stock_anterior, stock_resultante, motivo)
    VALUES (
        p_id_producto, p_id_sucursal, p_id_usuario, p_tipo,
        CASE WHEN p_tipo = 'SALIDA' THEN -p_cantidad ELSE p_cantidad END,
        v_stock_anterior, v_stock_resultante,
        p_motivo
    )
    RETURNING id_movimiento INTO v_movimiento_id;

    RETURN v_movimiento_id;
END;
$$;

-- Ajusta el stock total de un producto repartiendolo entre sucursales (transaccion)
-- p_distribucion: [{ id_inventario, id_sucursal, stock_anterior, nuevo_stock, cantidad }]
CREATE OR REPLACE FUNCTION public.ajustar_stock_total(
    p_id_producto BIGINT,
    p_id_usuario BIGINT,
    p_motivo VARCHAR,
    p_distribucion JSONB
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_item  JSONB;
    v_id_inventario BIGINT;
BEGIN
    FOR v_item IN
        SELECT * FROM jsonb_array_elements(COALESCE(p_distribucion, '[]'::jsonb))
    LOOP
        v_id_inventario := (v_item->>'id_inventario')::BIGINT;

        IF v_id_inventario IS NULL THEN
            INSERT INTO public.inventario (id_producto, id_sucursal, stock_actual)
            VALUES (p_id_producto, (v_item->>'id_sucursal')::BIGINT, (v_item->>'nuevo_stock')::BIGINT)
            RETURNING id_inventario INTO v_id_inventario;
        ELSE
            UPDATE public.inventario
               SET stock_actual = (v_item->>'nuevo_stock')::BIGINT
             WHERE id_inventario = v_id_inventario;
        END IF;

        INSERT INTO public.movimiento_inventario
            (id_producto, id_sucursal, id_usuario, tipo, cantidad,
             stock_anterior, stock_resultante, motivo)
        VALUES (
            p_id_producto,
            (v_item->>'id_sucursal')::BIGINT,
            p_id_usuario,
            'AJUSTE',
            (v_item->>'cantidad')::BIGINT,
            (v_item->>'stock_anterior')::BIGINT,
            (v_item->>'nuevo_stock')::BIGINT,
            p_motivo
        );
    END LOOP;
END;
$$;


