        'kpis', v_kpis,
        'charts', json_build_object(
            'salesByBranch', v_ventas_por_sucursal,
            'ordersByEstado', v_pedidos_por_estado,
            'productsByCategory', v_productos_por_categoria,
            'lowStock', v_low_stock
        )
    );
END;
$$;


