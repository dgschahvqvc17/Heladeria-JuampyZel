CREATE OR REPLACE FUNCTION public.reporte_ventas_resumen(
    p_fecha_desde TEXT DEFAULT NULL,
    p_fecha_hasta TEXT DEFAULT NULL,
    p_id_sucursal BIGINT DEFAULT NULL
)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_desde     TIMESTAMPTZ;
    v_hasta     TIMESTAMPTZ;
    v_totales   JSON;
    v_por_sucursal JSON;
    v_por_producto  JSON;
    v_por_dia       JSON;
BEGIN
    IF p_fecha_desde IS NOT NULL AND p_fecha_desde <> '' THEN
        v_desde := (p_fecha_desde || ' 00:00:00')::TIMESTAMPTZ;
    END IF;
    IF p_fecha_hasta IS NOT NULL AND p_fecha_hasta <> '' THEN
        v_hasta := (p_fecha_hasta || ' 23:59:59')::TIMESTAMPTZ;
    END IF;

    SELECT json_build_object(
               'total_ventas', COUNT(*),
               'total_ingresos', ROUND(COALESCE(SUM(v.total), 0)::NUMERIC, 2)
           )
      INTO v_totales
      FROM public.venta v
     WHERE (v_desde IS NULL OR v.fecha_venta >= v_desde)
       AND (v_hasta IS NULL OR v.fecha_venta <= v_hasta)
       AND (p_id_sucursal IS NULL OR v.id_sucursal = p_id_sucursal);

    SELECT COALESCE(json_agg(json_build_object('name', t.name, 'value', t.value) ORDER BY t.value DESC), '[]'::json)
      INTO v_por_sucursal
      FROM (
          SELECT s.nombre AS name, COUNT(*) AS value
          FROM public.venta v
          INNER JOIN public.sucursal s ON s.id_sucursal = v.id_sucursal
          WHERE (v_desde IS NULL OR v.fecha_venta >= v_desde)
            AND (v_hasta IS NULL OR v.fecha_venta <= v_hasta)
            AND (p_id_sucursal IS NULL OR v.id_sucursal = p_id_sucursal)
          GROUP BY s.id_sucursal, s.nombre
      ) t;

    SELECT COALESCE(json_agg(json_build_object('name', t.name, 'value', t.value) ORDER BY t.value DESC), '[]'::json)
      INTO v_por_producto
      FROM (
          SELECT p.nombre AS name, SUM(dv.cantidad) AS value
          FROM public.detalle_venta dv
          INNER JOIN public.venta v ON v.id_venta = dv.id_venta
          INNER JOIN public.producto p ON p.id_producto = dv.id_producto
          WHERE (v_desde IS NULL OR v.fecha_venta >= v_desde)
            AND (v_hasta IS NULL OR v.fecha_venta <= v_hasta)
            AND (p_id_sucursal IS NULL OR v.id_sucursal = p_id_sucursal)
          GROUP BY p.id_producto, p.nombre
          ORDER BY value DESC
          LIMIT 10
      ) t;

    SELECT COALESCE(json_agg(json_build_object('date', t.date, 'total', t.total) ORDER BY t.date), '[]'::json)
      INTO v_por_dia
      FROM (
          SELECT (v.fecha_venta::date)::text AS date,
                 ROUND(COALESCE(SUM(v.total), 0)::NUMERIC, 2) AS total
          FROM public.venta v
          WHERE (v_desde IS NULL OR v.fecha_venta >= v_desde)
            AND (v_hasta IS NULL OR v.fecha_venta <= v_hasta)
            AND (p_id_sucursal IS NULL OR v.id_sucursal = p_id_sucursal)
          GROUP BY v.fecha_venta::date
      ) t;

    RETURN json_build_object(
        'totals', v_totales,
        'byBranch', v_por_sucursal,
        'byProduct', v_por_producto,
        'byDay', v_por_dia
    );
END;
$$;

