CREATE OR REPLACE FUNCTION public.reporte_productos_resumen()
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_totales   JSON;
    v_por_categoria JSON;
    v_low_stock JSON;
BEGIN
    SELECT json_build_object(
               'total_productos', COUNT(*),
               'productos_activos', COUNT(*) FILTER (WHERE p.estado),
               'productos_inactivos', COUNT(*) FILTER (WHERE NOT p.estado)
           )
      INTO v_totales
      FROM public.producto p;

    SELECT COALESCE(json_agg(json_build_object('name', t.name, 'value', t.value) ORDER BY t.value DESC), '[]'::json)
      INTO v_por_categoria
      FROM (
          SELECT c.nombre AS name, COUNT(p.id_producto) AS value
          FROM public.categoria c
          LEFT JOIN public.producto p ON p.id_categoria = c.id_categoria
          GROUP BY c.id_categoria, c.nombre
      ) t;

    SELECT COALESCE(json_agg(json_build_object(
               'id_producto', t.id_producto,
               'nombre', t.nombre,
               'precio', t.precio,
               'stock_minimo', t.stock_minimo,
               'stock_total', t.stock_total
           ) ORDER BY t.stock_total, t.nombre), '[]'::json)
      INTO v_low_stock
      FROM (
          SELECT p.id_producto, p.nombre, ROUND(p.precio::NUMERIC, 2) AS precio,
                 p.stock_minimo,
                 COALESCE(SUM(i.stock_actual), 0) AS stock_total
          FROM public.producto p
          LEFT JOIN public.inventario i ON i.id_producto = p.id_producto
          WHERE p.estado = TRUE
          GROUP BY p.id_producto, p.nombre, p.precio, p.stock_minimo
          HAVING COALESCE(SUM(i.stock_actual), 0) < p.stock_minimo
      ) t;

    RETURN json_build_object('totals', v_totales, 'byCategory', v_por_categoria, 'lowStock', v_low_stock);
END;
$$;

