-- Genera alertas de stock bajo (INSERT...SELECT sin duplicar PENDIENTES)
CREATE OR REPLACE FUNCTION public.generar_alertas_stock()
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_count BIGINT := 0;
BEGIN
    WITH nuevas AS (
        INSERT INTO public.alerta_stock (id_inventario)
        SELECT i.id_inventario
        FROM public.inventario i
        INNER JOIN public.producto p ON p.id_producto = i.id_producto
        WHERE i.stock_actual <= p.stock_minimo
          AND p.estado = TRUE
          AND NOT EXISTS (
              SELECT 1 FROM public.alerta_stock a
              WHERE a.id_inventario = i.id_inventario
                AND a.estado = 'PENDIENTE'
          )
        RETURNING 1
    )
    SELECT COUNT(*) INTO v_count FROM nuevas;

    RETURN v_count;
END;
$$;

-- Registro de venta: venta + detalle + descuento de stock (transaccion)
CREATE OR REPLACE FUNCTION public.registrar_venta(
    p_id_cliente BIGINT,
    p_id_usuario BIGINT,
    p_id_sucursal BIGINT,
    p_total NUMERIC,
    p_detalles JSONB DEFAULT '[]'
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_venta_id     BIGINT;
    v_detalle      JSONB;
    v_id_producto  BIGINT;
    v_cantidad     BIGINT;
    v_stock        BIGINT;
    v_afectados    BIGINT;
BEGIN
    INSERT INTO public.venta (id_cliente, id_usuario, id_sucursal, total)
    VALUES (p_id_cliente, p_id_usuario, p_id_sucursal, p_total)
    RETURNING id_venta INTO v_venta_id;

    FOR v_detalle IN
        SELECT * FROM jsonb_array_elements(COALESCE(p_detalles, '[]'::jsonb))
    LOOP
        v_id_producto := (v_detalle->>'id_producto')::BIGINT;
        v_cantidad    := (v_detalle->>'cantidad')::BIGINT;

        INSERT INTO public.detalle_venta
            (id_venta, id_producto, cantidad, precio_unitario, subtotal)
        VALUES (
            v_venta_id,
            v_id_producto,
            v_cantidad,
            (v_detalle->>'precio_unitario')::NUMERIC(10,2),
            (v_detalle->>'subtotal')::NUMERIC(10,2)
        );

        UPDATE public.inventario
           SET stock_actual = stock_actual - v_cantidad
         WHERE id_producto = v_id_producto
           AND id_sucursal = p_id_sucursal
         RETURNING stock_actual INTO v_stock;

        GET DIAGNOSTICS v_afectados = ROW_COUNT;

        IF v_afectados = 0 THEN
            RAISE EXCEPTION 'Stock insuficiente: el producto % no tiene inventario en la sucursal', v_id_producto;
        END IF;

        IF v_stock < 0 THEN
            RAISE EXCEPTION 'Stock insuficiente para el producto %', v_id_producto;
        END IF;
    END LOOP;

    RETURN v_venta_id;
END;
$$;

-- Registro de pedido: pedido + detalle + historial PENDIENTE (transaccion)
CREATE OR REPLACE FUNCTION public.registrar_pedido(
    p_id_tienda BIGINT,
    p_id_usuario BIGINT,
    p_total NUMERIC,
    p_detalles JSONB DEFAULT '[]'
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
